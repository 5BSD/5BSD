# Emit one syscall stub. Make and native build rules supply the same configured
# macro, symbol and printf-format architecture notes; no syscall list lives here.
set -eu
if [ "$#" -ne 4 ]; then
    echo "usage: gen-syscall.sh macro symbol stack-note feature-note" >&2
    exit 1
fi
case "$1" in RSYSCALL|PSEUDO) ;; *) echo "invalid syscall macro" >&2; exit 1 ;; esac
case "$2" in ''|[0-9]*|*[!a-zA-Z0-9_]*) echo "invalid syscall symbol" >&2; exit 1 ;; esac
printf '/* %sgenerated by libsys/Makefile.sys */\n' @
printf '#include "compat.h"\n#include "SYS.h"\n%s(%s)\n' "$1" "$2"
# These are maintained printf formats, including %% in the stack-note format.
printf "$3"
printf "$4"
