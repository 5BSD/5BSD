#!/usr/local/bin/python3.12
"""Refresh 5BSD zsh build inputs and remove tests for excluded modules."""
from pathlib import Path
import re, shutil, sys, shlex
src=Path(sys.argv[1]).resolve()
build=Path(sys.argv[2]).resolve()
out=Path(sys.argv[3]).resolve()
gen=out/'generated'
gen.mkdir(parents=True,exist_ok=True)
# Preserve upstream relative includes in module headers.
for p in (build/'Src').rglob('*'):
 if p.is_file() and (p.suffix in ('.h','.mdh','.epro','.pro') or p.name in ('bltinmods.list','widgets.list','thingies.list')):
  dest=gen/p.relative_to(build)
  dest.parent.mkdir(parents=True,exist_ok=True)
  shutil.copyfile(p,dest)
config=(build/'config.h').read_text()
# The target ABI, not the host used to refresh headers, chooses integer types.
for name in ['LONG_IS_64_BIT','MACHTYPE','VENDOR','OSTYPE','ZSH_64_BIT_TYPE','ZSH_64_BIT_UTYPE','ZLONG_IS_LONG_64','ZLONG_IS_LONG_LONG','RLIM_T_IS_LONG_LONG','RLIM_T_IS_QUAD_T']:
 config=re.sub(r'^#define '+name+r' .*$', '/* '+name+' is selected below. */',config,flags=re.M)
config+='''
/* 5BSD target ABI; this header is also used by cross builds. */
#define VENDOR "5BSD"
#define OSTYPE "freebsd"
#if __SIZEOF_LONG__ == 8
#define ZSH_64_BIT_TYPE long
#define ZSH_64_BIT_UTYPE unsigned long
#define ZLONG_IS_LONG_64 1
#define LONG_IS_64_BIT 1
#else
#define ZSH_64_BIT_TYPE long long
#define ZSH_64_BIT_UTYPE unsigned long long
#define ZLONG_IS_LONG_LONG 1
#define RLIM_T_IS_LONG_LONG 1
#define INO_T_IS_64_BIT 1
#define OFF_T_IS_64_BIT 1
#endif
'''
(gen/'config.h').write_text(config)
# Signal numbers come from target headers at build time.
for name in ('signames.c','sigcount.h','Modules/errcount.h'):
 p=gen/'Src'/name
 if p.exists(): p.unlink()
modules=[]
patterns=[]
for line in (build/'config.modules').read_text().splitlines():
 if not line or line.startswith('#'): continue
 head, _, fns = line.partition(' functions=')
 fields=dict(x.split('=',1) for x in shlex.split(head))
 fields['functions']=fns
 if fields['link']=='no': continue
 assert fields['link']=='static',line
 mdd=src/fields['modfile']
 data=mdd.read_text()
 match=re.search(r'^objects="(.*?)"',data,re.M|re.S)
 if match:
  for obj in match[1].replace('\\\n','').split():
   modules.append((mdd.parent/(obj[:-2]+'.c')).relative_to(src).as_posix())
 patterns+=shlex.split(fields.get('functions',''))
modules.append('Src/main.c')
assert len({Path(x).name for x in modules})==len(modules)
(out/'sources.mk').write_text('# Generated by import-build.py; see README.\nSRCS= '+ ' \\\n\t'.join(Path(x).name for x in modules)+'\n')
functions={}
for pattern in patterns:
 for p in src.glob(pattern):
  if not p.is_file() or p.name.startswith('.') or p.name.endswith('~'): continue
  if p.name in {'_darcs', '_osc', '_qdbus', '_zypper'}:
   continue # GPL-licensed optional completions.
  assert p.name not in functions or functions[p.name]==p, p
  functions[p.name]=p
(out/'functions.mk').write_text('# Generated by import-build.py; see README.\nFILES= '+ ' \\\n\t'.join('${ZSHSRC}/'+p.relative_to(src).as_posix() for p in sorted(functions.values()))+'\nFILESDIR= ${SHAREDIR}/zsh/functions\n')
# These modules are intentionally excluded from 5BSD's base shell.
# Do not reintroduce their test groups when refreshing the vendor release.
for name in ('V07pcre.ztst', 'V11db_gdbm.ztst'):
 (src/'Test'/name).unlink(missing_ok=True)
print(f'Imported headers for {len(modules)} sources and {len(functions)} functions')
