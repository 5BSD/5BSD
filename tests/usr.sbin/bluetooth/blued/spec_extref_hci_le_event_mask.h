/*
 * EXTERNAL REFERENCE ORACLE: the HCI LE Event Mask -- bit assignments, the
 * specified default, the "Controller shall ignore unsupported bits" rule, and
 * the three reference stacks' gating strategies.
 *
 * Hand-written.  Every value and every claim below is traceable to a named
 * external source; nothing here was derived from blued, and no value was
 * produced by running 5BSD code.
 *
 * WHY THIS HEADER EXISTS
 * ----------------------
 * blued builds its LE event mask by hand in hci_le_default_event_mask() and
 * gates individual bits on LE FEATURE bits.  Two things make that error-prone,
 * and both are recorded here so a test can pin them:
 *
 *   1. The mask bit numbering and the LE feature bit numbering are DIFFERENT
 *      numbering spaces.  A bit gated on the wrong feature is silently lost:
 *      the command still succeeds, and the event simply never arrives.
 *
 *   2. Gating is not required at all.  Section 7.8.1 obliges the Controller to
 *      ignore bits it does not support, so an ungated mask is legal and safe.
 *      Gating can therefore only LOSE events; it can never protect the host.
 *      This is the asymmetry that makes a wrong gate a one-way failure.
 *
 * A masked event is not merely "not delivered".  For bit 5 the Link Layer is
 * required to REJECT the peer's procedure on the air -- see
 * BT_EXTREF_LE_EVTMASK_BIT5_MASKED_LL_REJECT_ERROR below.
 *
 * SPEC
 * ----
 * /usr/src/bluetooth-specs/Core_Specification_6_3.txt
 *
 *   Vol 4, Part E, Section 7.8.1 "LE Set Event Mask command"
 *   (text lines 111760-111800 and the bit table at 111800-111860).
 *
 *   Description, verbatim (text lines 111768-111780):
 *     "This command is used to control which LE events are generated by the
 *      HCI for the Host. If the bit in the LE_Event_Mask is set to a one, then
 *      the event associated with that bit will be enabled."
 *     "The Controller shall ignore those bits which are reserved for future
 *      use or represent events which it does not support. If the Host sets any
 *      of these bits to 1, the Controller shall act as if they were set to 0."
 *     "For LE events to be generated, the LE Meta event bit in the Event_Mask
 *      shall also be set. If that bit is not set, then LE events shall not be
 *      generated, regardless of how the LE_Event_Mask is set."
 *
 *   Default, verbatim (text line ~111857):
 *     "The value with all bits set to 0 indicates that no events are
 *      specified. The default is for just bits 0 to 4 to be set."
 *
 *   Vol 6, Part B, Section 5.1.7.2 "Responding to LL_CONNECTION_PARAM_REQ and
 *   LL_CONNECTION_PARAM_RSP PDUs" (text lines 143896-143901), verbatim:
 *     "If the request is being indicated to the Host and the event to the Host
 *      is masked, then the Link Layer shall issue an LL_REJECT_EXT_IND PDU
 *      with the ErrorCode set to Unsupported Remote Feature (0x1A). The
 *      initiating device may retry in case this is a temporary situation. If
 *      the request is not being indicated to the Host, then the event mask
 *      shall be ignored."
 *
 *   Vol 4, Part E, Section 7.7.65.25 "LE CIS Established event" (text lines
 *   107560-107564), verbatim:
 *     "This event indicates that a CIS has been established, was considered
 *      lost before being established, or--on the Central--was rejected by the
 *      Peripheral. It is generated by the Controller in the Central and
 *      Peripheral."
 *   -- i.e. this event is NOT central-only, so gating its mask bit on a
 *   central-only feature bit loses it on a peripheral.
 *
 * REFERENCE IMPLEMENTATIONS
 * -------------------------
 *   Apache NimBLE, github.com/apache/mynewt-nimble, snapshot commit
 *   1e8ed60276f35a80ed4d4b4f8bb9d9c6fee53845:
 *     nimble/host/src/ble_hs_startup.c:212-330 -- gates the mask on the HCI
 *     VERSION read by ble_hs_startup_read_local_ver_tx()
 *     (ble_hs_startup.c:53, called at :411), not on feature bits.  Bit 5 is
 *     set for any controller reporting >= 4.1 (:220-225); bits 10 and 19 are
 *     set at >= 4.2 and >= 5.0 respectively (:227-235, :237-251).
 *
 *   Zephyr, github.com/zephyrproject-rtos/zephyr, snapshot commit
 *   2665fcca3cced3aefb7202d6289991d8cc1dfcac:
 *     subsys/bluetooth/host/hci_core.c:3765-3766 -- sets bit 5 gated on the LE
 *     feature bit for the Connection Parameters Request Procedure:
 *         if (BT_FEAT_LE_CONN_PARAM_REQ_PROC(bt_dev.le.features)) {
 *                 mask |= BT_EVT_MASK_LE_CONN_PARAM_REQ;
 *     include/zephyr/bluetooth/hci_types.h:4584 defines that mask as
 *     BT_EVT_BIT(5); :163 and :221-222 define the FEATURE bit as 1.  The two
 *     numbers differ, which is precisely the trap this header records.
 *     Zephyr also implements the event (hci_core.c:3075) and both replies
 *     (hci_core.c:2082, :2105).
 *
 *   BlueZ, git.kernel.org/pub/scm/bluetooth/bluez.git, snapshot commit
 *   92305dc06ab8a6d89af2dae1d725cc4d51462ad1:
 *     BlueZ is host-only over the Linux kernel; the LE event mask is set by
 *     the kernel, not by BlueZ userspace, so BlueZ contributes no mask
 *     construction to compare.  It does read the Supported Commands bitmap
 *     (tools/btinfo.c:140, tools/hciconfig.c:1099).
 */
