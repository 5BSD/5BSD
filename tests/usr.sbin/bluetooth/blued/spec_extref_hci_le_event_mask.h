/*
 * The highest mask bit that a 5.2 + Connection Subrating host may need.
 * Bit 34 (Subrate Change) is the Connection Subrating addition.
 */
#define BT_EXTREF_LE_EVTMASK_MAX_BIT_IN_SCOPE		34

/*
 * "The default is for just bits 0 to 4 to be set."  Section 7.8.1, text line
 * ~111857.  Any subevent above bit 4 that a host wants MUST be unmasked
 * explicitly; there is no implicit enablement.
 */
#define BT_EXTREF_LE_EVTMASK_SPEC_DEFAULT		UINT64_C(0x000000000000001f)

/*
 * Section 7.8.1: "The Controller shall ignore those bits which are reserved
 * for future use or represent events which it does not support."  1 = setting
 * a bit for an unsupported event is safe and cannot fail the command.
 *
 * Consequence for a test: a host is never REQUIRED to gate a mask bit on a
 * feature bit, so a missing gate is not a defect, but a WRONG gate always is.
 */
#define BT_EXTREF_LE_EVTMASK_UNSUPPORTED_BITS_IGNORED	1

/*
 * Section 7.8.1: LE events are gated a second time by the LE Meta event bit in
 * the (non-LE) Event_Mask.  Vol 4, Part E, Section 7.3.1, LE Meta event is
 * bit 61.
 */
#define BT_EXTREF_EVTMASK_LE_META_BIT			61

/*
 * Vol 6, Part B, Section 5.1.7.2: the on-air consequence of leaving bit 5
 * masked when the peer runs the Connection Parameters Request procedure and
 * the Link Layer needs to consult the Host.  This is why bit 5 is not
 * cosmetic.
 */
#define BT_EXTREF_LE_EVTMASK_BIT5_MASKED_LL_REJECT_ERROR	0x1a	/* Unsupported
								   Remote
								   Feature */

/*
 * Which subevents a host must ALSO be able to act on once it unmasks the bit.
 * Bit 5 is the only one in the in-scope range that obliges the host to answer
 * with a command; if it is unmasked and not answered, the peer's procedure
 * stalls until its LL procedure response timeout.
 *
 * OCFs from Vol 4, Part E, Sections 7.8.31 and 7.8.32 (OGF 0x08).
 */
#define BT_EXTREF_LE_OCF_REMOTE_CONN_PARAM_REQ_REPLY	0x0020
#define BT_EXTREF_LE_OCF_REMOTE_CONN_PARAM_REQ_NEG_REPLY 0x0021

/*
 * Reference gating strategy.  0 = does not gate (or does not build the mask),
 * 1 = gates on the HCI version, 2 = gates on LE feature bits.
 *
 * Recorded because the two gating strategies disagree about controllers that
 * report a high HCI version but clear the corresponding feature bit, and
 * because a reader comparing 5BSD against only one reference would conclude
 * the other strategy is wrong.  Section 7.8.1 permits either, and permits
 * neither.
 */
#define BT_EXTREF_LE_EVTMASK_GATING_NIMBLE		1	/* ble_hs_startup.c:206,212-330 */
#define BT_EXTREF_LE_EVTMASK_GATING_ZEPHYR		2	/* hci_core.c:3765-3766 */
#define BT_EXTREF_LE_EVTMASK_GATING_BLUEZ		0	/* kernel-side */

/*
 * Bits that NimBLE sets for every controller at or above the stated HCI
 * version, transcribed from ble_hs_startup.c:212-251.  A host targeting the
 * same controller population and NOT setting these is delivering strictly
 * fewer events than the most conservative reference.
 */
#define BT_EXTREF_LE_EVTMASK_NIMBLE_AT_4_1		UINT64_C(0x000000000000003f)
#define BT_EXTREF_LE_EVTMASK_NIMBLE_AT_4_2		UINT64_C(0x000000000000067f)
#define BT_EXTREF_LE_EVTMASK_NIMBLE_AT_5_0		UINT64_C(0x00000000000ffe7f)

