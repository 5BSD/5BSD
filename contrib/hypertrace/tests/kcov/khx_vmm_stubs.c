/*
 * Audited panic stubs for the amd64 VMM HyperTrace suite.  These kernel
 * symbols are referenced by vmm.c, vmm_vm.c, x86.c and vmm_dev_machdep.c
 * but lie outside the paths the suite drives: device-model I/O (vatpic,
 * vioapic, vhpet, vrtc, vlapic interrupt delivery), PCI passthrough and
 * IOMMU mapping, instruction fetch/decode/emulation, the startup-event
 * state machine and event checkpointing, FPU/xsave switching, dirty-log
 * export, statistics export, sleepqueues of the run loop, environment
 * lookups, and (vmm_dev.c) memory segments, devmem mapping, NUMA domain
 * policy, event checkpoints, startup requests and the MAC memory and
 * passthrough checks.  Each stub panics: reaching one is a harness failure, never a
 * silent no-op.  The list is exactly the build's unresolved-symbol set
 * after the functional shims in khx_vmm.c.  This file deliberately
 * includes no kernel headers (each stub has the uniform type below).
 * Not production code.
 */
