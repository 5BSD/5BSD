#ifndef _VIRTIO_DTRACE_H_
#define _VIRTIO_DTRACE_H_

#include <sys/queue.h>
#include <sys/dtrace_bsd.h>
#include <dev/dttransport/dttransport.h>
#include <dev/virtio/dtrace/virtio_dtrace_wire.h>

/*
 * Installation observations travel from guest to host; matching host
 * acceptance events travel back to the guest.
 *
 * On the other hand, provider registration, probe creation/deletion and
 * provider de-registration is meant only for the host.
 *
 * READY and EOF are used for synchronization for purposes, while CLEANUP will
 * be used to clean up the TX virtqueue on the guest.
 */
#define	VIRTIO_DTRACE_DEVICE_READY	VTDTR_WIRE_EVENT_READY /* The device is ready */
#define	VIRTIO_DTRACE_REGISTER		VTDTR_WIRE_EVENT_REGISTER /* UNUSED */
#define	VIRTIO_DTRACE_UNREGISTER	VTDTR_WIRE_EVENT_UNREGISTER /* UNUSED */
#define	VIRTIO_DTRACE_DESTROY		VTDTR_WIRE_EVENT_DESTROY /* UNUSED */
#define	VIRTIO_DTRACE_PROBE_CREATE	VTDTR_WIRE_EVENT_PROBE_CREATE /* UNUSED */
#define	VIRTIO_DTRACE_PROBE_INSTALL	VTDTR_WIRE_EVENT_PROBE_INSTALL /* Probe Installation */
#define	VIRTIO_DTRACE_PROBE_UNDEFINED	VTDTR_WIRE_EVENT_RESERVED_06 /* Undefined */
#define	VIRTIO_DTRACE_EOF		VTDTR_WIRE_EVENT_EOF /* EOF Signal */
#define	VIRTIO_DTRACE_GO		VTDTR_WIRE_EVENT_GO /* Start tracing */
#define	VIRTIO_DTRACE_ELF		VTDTR_WIRE_EVENT_ELF /* ELF file transmission */
#define	VIRTIO_DTRACE_STOP		VTDTR_WIRE_EVENT_STOP /* Start tracing */
#define	VIRTIO_DTRACE_KILL		VTDTR_WIRE_EVENT_KILL /* Kill a DTrace process */
#define	VIRTIO_DTRACE_CLEANUP_DTRACED	VTDTR_WIRE_EVENT_CLEANUP_DTRACED /* Clean up dtraced state. */
#define	VIRTIO_DTRACE_NODE_ID		VTDTR_WIRE_EVENT_NODE_ID /* Negotiate DTrace node ID */
#define	VIRTIO_DTRACE_INSTALLED	VTDTR_WIRE_EVENT_INSTALLED /* Guest observed installation */
#define	VIRTIO_DTRACE_UNINSTALLED VTDTR_WIRE_EVENT_UNINSTALLED /* Guest tracing child exited */
#define VIRTIO_DTRACE_HOST_INSTALLED VTDTR_WIRE_EVENT_HOST_INSTALLED /* Host accepted install observation */
#define VIRTIO_DTRACE_HOST_UNINSTALLED VTDTR_WIRE_EVENT_HOST_UNINSTALLED /* Host accepted exit observation */
#define VIRTIO_DTRACE_STATUS VTDTR_WIRE_EVENT_STATUS /* Query host delivery phase */
#define VIRTIO_DTRACE_HOST_STATUS VTDTR_WIRE_EVENT_HOST_STATUS /* Durable phase or unavailable */
#define VIRTIO_DTRACE_HOST_ELF VTDTR_WIRE_EVENT_HOST_ELF /* Host daemon accepted guest ELF */
#define VIRTIO_DTRACE_INGRESS_STATUS VTDTR_WIRE_EVENT_INGRESS_STATUS /* Query host guest-ELF ingest */
#define VIRTIO_DTRACE_HOST_INGRESS_STATUS VTDTR_WIRE_EVENT_HOST_INGRESS_STATUS /* Host ingest phase */
#define VIRTIO_DTRACE_KILL_APPLIED VTDTR_WIRE_EVENT_KILL_APPLIED
#define VIRTIO_DTRACE_HOST_KILL_APPLIED VTDTR_WIRE_EVENT_HOST_KILL_APPLIED
#define VIRTIO_DTRACE_NODE_REKEY VTDTR_WIRE_EVENT_NODE_REKEY
#define VIRTIO_DTRACE_REKEY_COMMIT VTDTR_WIRE_EVENT_REKEY_COMMIT
#define VIRTIO_DTRACE_REKEY_COMMITTED VTDTR_WIRE_EVENT_REKEY_COMMITTED
#define VIRTIO_DTRACE_REKEY_APPLIED VTDTR_WIRE_EVENT_REKEY_APPLIED
#define VIRTIO_DTRACE_REKEY_DELIVERY_QUERY VTDTR_WIRE_EVENT_REKEY_DELIVERY_QUERY
#define VIRTIO_DTRACE_REKEY_INGRESS_QUERY VTDTR_WIRE_EVENT_REKEY_INGRESS_QUERY
#define VIRTIO_DTRACE_REKEY_KILL_QUERY VTDTR_WIRE_EVENT_REKEY_KILL_QUERY
#define VIRTIO_DTRACE_REKEY_DELIVERY_RECEIPT VTDTR_WIRE_EVENT_REKEY_DELIVERY_RECEIPT
#define VIRTIO_DTRACE_REKEY_INGRESS_RECEIPT VTDTR_WIRE_EVENT_REKEY_INGRESS_RECEIPT
#define VIRTIO_DTRACE_REKEY_KILL_RECEIPT VTDTR_WIRE_EVENT_REKEY_KILL_RECEIPT
#define VIRTIO_DTRACE_CLEANUP_APPLIED VTDTR_WIRE_EVENT_CLEANUP_APPLIED
#define VIRTIO_DTRACE_HOST_CLEANUP_APPLIED VTDTR_WIRE_EVENT_HOST_CLEANUP_APPLIED
#define VIRTIO_DTRACE_SESSION_STOP VTDTR_WIRE_EVENT_SESSION_STOP
#define VIRTIO_DTRACE_SESSION_STOPPED VTDTR_WIRE_EVENT_SESSION_STOPPED
#define VIRTIO_DTRACE_SESSION_PREPARE VTDTR_WIRE_EVENT_SESSION_PREPARE
#define VIRTIO_DTRACE_SESSION_READY VTDTR_WIRE_EVENT_SESSION_READY
#define VIRTIO_DTRACE_SESSION_COMMIT VTDTR_WIRE_EVENT_SESSION_COMMIT
#define VIRTIO_DTRACE_SESSION_ACTIVE VTDTR_WIRE_EVENT_SESSION_ACTIVE


#endif
