"""Exercise shared syscall generator argument and architecture-note semantics."""
from pathlib import Path
import subprocess
import unittest

SCRIPT = Path(__file__).resolve().parents[3] / 'lib/libsys/gen-syscall.sh'


class Generator(unittest.TestCase):
    def run_generator(self, *args):
        return subprocess.run(['/bin/sh', str(SCRIPT), *args], capture_output=True, text=True)

    def test_macros_and_literal_symbol(self):
        for macro, symbol in [('RSYSCALL', 'getpid'), ('PSEUDO', '__realpathat')]:
            result = self.run_generator(macro, symbol, '\\t.section .note.GNU-stack,"",%%progbits\\n', '')
            self.assertEqual(result.returncode, 0)
            self.assertEqual(result.stdout, '/* @generated by libsys/Makefile.sys */\n#include "compat.h"\n#include "SYS.h"\n' + macro + '(' + symbol + ')\n\t.section .note.GNU-stack,"",%progbits\n')

    def test_note_input_preserved(self):
        note = '#include <sys/elf_common.h>\\nFEATURE_NOTE(value)\\n'
        result = self.run_generator('RSYSCALL', 'sample', '', note)
        self.assertEqual(result.returncode, 0)
        self.assertTrue(result.stdout.endswith('#include <sys/elf_common.h>\nFEATURE_NOTE(value)\n'))

    def test_invalid_arguments(self):
        for args in [(), ('BAD', 'name', '', ''), ('PSEUDO', '1name', '', ''),
                     ('RSYSCALL', 'name);bad', '', '')]:
            with self.subTest(args=args):
                result = self.run_generator(*args)
                self.assertNotEqual(result.returncode, 0)
                self.assertEqual(result.stdout, '')


if __name__ == '__main__':
    unittest.main()
