"""Generate secureboot headers from declared policy and public certificate files.

PEM framing is checked here; cryptographic decoding remains the verifier's job.
No trust discovery, signer access, wall clock or input mtime is used.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re


def public_pem(paths, required):
    result = bytearray()
    count = 0
    for path in paths:
        data = Path(path).read_bytes()
        inside = False
        body = False
        for line in data.split(b'\n'):
            line = line.removesuffix(b'\r')
            if not line.strip(b' \t'):
                continue
            if line == b'-----BEGIN CERTIFICATE-----' and not inside:
                inside, body = True, False
            elif line == b'-----END CERTIFICATE-----' and inside and body:
                inside = False
                count += 1
            elif inside and re.fullmatch(rb'[A-Za-z0-9+/=]+', line):
                body = True
            else:
                raise ValueError('invalid public trust framing: ' + str(path))
        if inside:
            raise ValueError('incomplete public certificate: ' + str(path))
        result.extend(data)
    if required and not count:
        raise ValueError('public certificates required')
    return bytes(result)


def c_array(name, data):
    # Match file2c -sx formatting as well as the actual embedded bytes.
    out = 'static const char ' + name + '[] = {\n'
    count = position = 0
    for byte in data:
        if count:
            out += ','
            position += 1
        if position > 70:
            out += '\n'
            count = position = 0
        if count:
            out += ' '
            position += 1
        else:
            out += '\t'
            position += 8
        out += f'0x{byte:02x}'
        position += 4
        count += 1
    return out + '\n};\n'


def c_string(value):
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92)
                         else '\\%03o' % b for b in value.encode('utf-8')) + '"'


def generate(policy, anchors, verification):
    keys = {'format', 'build_utc', 'hashes', 'signatures', 'signature_extensions',
            'require_public_anchors', 'compiled_trust_only', 'self_tests', 'hash_kat'}
    if set(policy) != keys or type(policy['format']) is not int or policy['format'] != 1:
        raise ValueError('expected explicit format-1 trust policy')
    if type(policy['build_utc']) is not int or not 0 <= policy['build_utc'] <= 2**63 - 1:
        raise ValueError('build_utc must be a nonnegative signed 64-bit integer')
    for key in ('require_public_anchors', 'compiled_trust_only', 'self_tests'):
        if type(policy[key]) is not bool:
            raise ValueError(key + ' must be boolean')
    if policy['compiled_trust_only'] and not policy['require_public_anchors']:
        raise ValueError('compiled-only trust requires public anchors')
    for key, supported in [('hashes', {'SHA1', 'SHA256', 'SHA384', 'SHA512'}),
                           ('signatures', {'RSA', 'ECDSA'})]:
        values = policy[key]
        if not isinstance(values, list) or not values or any(type(x) is not str or x not in supported for x in values):
            raise ValueError('unsupported ' + key)
    extensions = policy['signature_extensions']
    if not isinstance(extensions, list) or not extensions or any(
            type(x) is not str or not re.fullmatch(r'[A-Za-z0-9_+-]+', x) for x in extensions):
        raise ValueError('invalid signature_extensions')
    if type(policy['hash_kat']) is not str or '\0' in policy['hash_kat']:
        raise ValueError('hash_kat must be a string without NUL')
    if verification and not policy['self_tests']:
        raise ValueError('verification certificates require self_tests')
    trust = public_pem(anchors, policy['require_public_anchors'])
    verify = public_pem(verification, False)
    preamble = '/* Autogenerated - DO NOT EDIT!!! */\n\n'
    ta = preamble + c_array('ta_PEM', trust + b'\0')
    config = ['#ifndef BSD_SECUREBOOT_CONFIG_H', '#define BSD_SECUREBOOT_CONFIG_H',
              '#define HAVE_BR_X509_TIME_CHECK 1', '#define TRUST_ANCHOR_STR ta_PEM']
    config += ['#define VE_' + x + '_SUPPORT 1'
               for x in sorted(set(policy['hashes'] + policy['signatures']))]
    if policy['compiled_trust_only']:
        config += ['#define VE_EFI_COMPILED_TRUST_ONLY 1']
    if policy['self_tests']:
        # Make emits one newline before and after the complete KAT block.
        ta += '\n'
        for algorithm in sorted(set(policy['hashes'])):
            digest = hashlib.new(algorithm.lower(), policy['hash_kat'].encode('utf-8')).hexdigest()
            ta += 'static char vh_' + algorithm + '[] = "' + digest + '";\n'
        ta += '\n' + c_array('vc_PEM', verify) + '\n'
        config += ['#define VERIFY_CERTS_STR vc_PEM', '#define VE_HASH_KAT_STRLEN strlen',
                   '#define VE_HASH_KAT_STR ' + c_string(policy['hash_kat'])]
    ta += '#define BUILD_UTC ' + str(policy['build_utc']) + '\n'
    # Match Make's current :O:u ordering, including duplicates removal.
    vse = preamble + 'static const char *signature_exts[] = {\n'
    vse += ''.join('"' + x + '",\n' for x in sorted(set(extensions))) + '\nNULL };\n'
    return {'ta.h': ta, 'vse.h': vse, 'secureboot_config.h': '\n'.join(config + ['#endif', ''])}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--policy', type=Path, required=True)
    parser.add_argument('--anchor', action='append', default=[])
    parser.add_argument('--verification', action='append', default=[])
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    result = generate(json.loads(args.policy.read_text()), args.anchor, args.verification)
    args.output.mkdir(parents=True, exist_ok=True)
    for name, data in result.items():
        (args.output / name).write_text(data)


if __name__ == '__main__':
    main()
