"""Maintain the installed native API and pinned support-header inventory."""
import argparse
import re
from collections import defaultdict
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--src',type=Path,default=Path('/usr/src'))
p.add_argument('--check',action='store_true')
a=p.parse_args()
s=a.src; r=s/'contrib/fuchsia'; d=s/'lib/libfidl'
groups=defaultdict(list); seen={}
roots=[r/'sdk/lib'/part/'include' for part in ['fidl_base','fidl/cpp','fidl/cpp/wire','fit','stdcompat','zircon-assert']]
roots += [r/'src/zircon/lib/zircon/include',r/'zircon/system/public']
# Follow every literal include in the native API and supported generator
# templates, including conditional branches. This is a source closure, not a
# list learned from one test binary. Do not install unrelated Zircon APIs or
# the unported Fuchsia dispatcher just because they share an include root.
for root in roots:
 for path in sorted(root.rglob('*')):
  if path.suffix not in ('.h','.inc') or not path.is_file(): continue
  relative=path.relative_to(root)
  if relative in seen and path.read_bytes()!=seen[relative].read_bytes():
   raise RuntimeError('conflicting installed header: '+str(relative))
  seen[relative]=path
seen[Path('lib/utf-utils/utf-utils.h')]=r/'sdk/lib/utf-utils/utf-utils.h'
reverse={path:relative for relative,path in seen.items()}
queue=list((d/'include/fidl/bsd').glob('*.h'))
queue += [r/'tools/fidl/fidlgen_cpp/codegen'/('file_'+name+'.tmpl') for name in
          ['natural_types_header','natural_types_source','common_types_header',
           'common_types_source','markers']]
visited=set(); needed=set()
while queue:
 path=queue.pop()
 if path in visited: continue
 visited.add(path)
 for name in re.findall(r'^\s*#\s*include\s*[<"]([^>"\n]+)[>"]',path.read_text(),re.M):
  relative=Path(name)
  if relative not in seen:
   relative=reverse.get((path.parent/name).resolve())
  if relative in seen:
   needed.add(relative)
   queue.append(seen[relative])
for relative in sorted(needed):
 path=seen[relative]
 groups[Path('fidl/support')/relative.parent].append('${SRCTOP}/'+str(path.relative_to(s)))
for path in sorted((d/'include/fidl/bsd').glob('*.h')):
 groups[Path('fidl/bsd')].append('${.CURDIR}/include/fidl/bsd/'+path.name)
out=['# SPDX-License-Identifier: BSD-2-Clause','# Generated by tools/build/fuchsia/update-runtime-headers.py; do not edit.','INCSGROUPS=']
# One shared prerequisite creates and records owned directories exactly once.
# .EXEC excludes this helper from the include install rules' .ALLSRC list.
directories=set()
for directory in groups:
 directories.update(parent for parent in directory.parents if str(parent)!='.')
 directories.add(directory)
out += ['fidl-header-directories: .EXEC .NOTMAIN',
        '\t${INSTALL} ${FIDL_HEADERS_0TAG_ARGS} -d -o ${BINOWN} -g ${BINGRP} -m 0755 '+
        ' '.join('${DESTDIR}${INCLUDEDIR}/'+str(path) for path in sorted(directories)),'']
for i,(directory,files) in enumerate(sorted(groups.items())):
 group='FIDL_HEADERS_'+str(i)
 out += ['INCSGROUPS+= '+group,group+'= '+' \\\n    '.join(files),group+'DIR= ${INCLUDEDIR}/'+str(directory),
         '_'+group+'INS: fidl-header-directories','']
text='\n'.join(out)+'\n'
output=d/'headers.mk'
if a.check:
 if output.read_text()!=text: raise SystemExit('headers.mk is stale; run update-runtime-headers.py')
else: output.write_text(text)
