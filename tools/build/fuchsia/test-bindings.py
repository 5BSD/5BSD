"""Regenerate or verify the checked-in FIDL bindings using the pinned host tools.

Every generated library directory gets a SOURCE.sha256 stamp naming the
SHA-256 of each input schema (relative to the source root) and, as comments,
the generator versions.  lib/libfidl/fidl-bindings.mk checks the schema lines
during buildworld with base tools only; this script (make -C
tools/build/fuchsia check) regenerates everything into a scratch tree and
diffs it, stamps included, against the checked-in trees.  `make -C
tools/build/fuchsia regen` (--write) replaces them.
"""
import argparse
import hashlib
import json
import os
import re
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--src', type=Path, default=Path('/usr/src'))
p.add_argument('--obj', type=Path, default=Path('/usr/obj/5bsd-fidl-runtime'))
p.add_argument('--tools', type=Path, default=Path('/usr/obj/5bsd-fidl'))
p.add_argument('--write', action='store_true', help='replace the checked-in fixtures')
a = p.parse_args()
os.environ['PYTHONDONTWRITEBYTECODE'] = '1'
a.obj.mkdir(parents=True, exist_ok=True)
projects = [
    ('runtime', a.src/'lib/libfidl/tests', ['zx.fidl', 'runtime.fidl']),
    ('timecmp', a.src/'lib/libtimecmp', ['timecmp.fidl']),
]
# Provider schemas: (name, directory, schema, dependency schemas).  zx.fidl
# names the native descriptor type (installed as /usr/share/fidl/zx.fidl).
ZX = a.src/'lib/libfidl/tests/zx.fidl'
providers = [
]
# Each migrated provider has a "next" schema for its evolve:1/evolve:2
# pairing test: at bsd:1 it must compile to exactly the production schema
# (same ordinals and layouts); at bsd:2 it adds methods only.
evolutions = [
]
projects += [(name, a.src/d, [*deps, f]) for name, d, f, deps in providers]
projects += [(name, a.src/d, [*deps, f], ['--available', 'bsd:2'])
             for name, d, f, _, deps in evolutions]


STAMP = 'SOURCE.sha256'


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generator_version():
    sources = json.loads((a.src/'tools/build/fuchsia/sources.json').read_text())
    revisions = sorted({m.group(1) for entry in sources['sources']
                        for m in [re.search(r'/\+archive/([0-9a-f]{40})/', entry['url'])]
                        if m})
    scripts = ['generate-bsd.py', 'generate_bsd_c.py', 'generate_bsd_c_types.py']
    lines = ['# generator: fidlc and fidlgen_cpp from fuchsia@' + ','.join(revisions)]
    lines += [f'# generator: {name} {sha256(a.src/"tools/build/fuchsia"/name)}'
              for name in scripts]
    return lines


def write_stamps(generated, inputs, extra):
    """Stamp each generated library directory with its inputs' hashes."""
    lines = ['# Generated by make -C tools/build/fuchsia regen; do not edit.',
             '# lib/libfidl/fidl-bindings.mk fails the build when a schema',
             '# below no longer matches; regenerate and commit the result.',
             *generator_version()]
    if extra:
        lines.append('# options: ' + ' '.join(extra))
    lines += [f'SHA256 ({path.resolve().relative_to(a.src.resolve())}) = {sha256(path)}'
              for path in inputs]
    for library in sorted((generated/'fidl').iterdir()):
        (library/STAMP).write_text('\n'.join(lines) + '\n')


def semantic(value):
    if isinstance(value, list):
        return [semantic(v) for v in value]
    if isinstance(value, dict):
        return {k: semantic(v) for k, v in value.items()
                if k not in ('location', 'maybe_attributes', 'deprecated',
                             'available', 'platform')}
    return value


def compatible(next_schema, production, deps, work):
    irs = []
    for tag, schema, extra in (('v1', next_schema, ['--available', 'bsd:1']),
                               ('prod', production, [])):
        out = work/(tag + '.json')
        files = []
        for dep in deps:
            files += ['--files', str(dep)]
        subprocess.run([str(a.tools/'fidlc'), '--json', str(out), *extra,
                        *files, '--files', str(schema)], check=True)
        irs.append(json.loads(out.read_text()))
    keys = [k for k in irs[1] if k.endswith('_declarations')] + ['declaration_order']
    return [k for k in keys if semantic(irs[0].get(k)) != semantic(irs[1].get(k))]
with tempfile.TemporaryDirectory(prefix='test-bindings-', dir=a.obj) as temporary:
    def contents(root):
        return {str(f.relative_to(root)): f.read_bytes()
                for f in root.rglob('*') if f.is_file()}
    outputs, differences, count = [], [], 0
    for name, d, f, production, deps in evolutions:
        work = Path(temporary)/(name + '-v1')
        work.mkdir()
        bad = compatible(a.src/d/f, a.src/production, deps, work)
        if bad:
            p.exit(1, f'{name}: bsd:1 differs from {production} in: {bad}\n')
    for name, source, schemas, *extra in projects:
        work = Path(temporary)/name
        work.mkdir()
        ir, generated, destination = work/'schema.json', work/'generated', source/'generated'
        command = [str(a.tools/'fidlc'), '--json', str(ir), *(extra[0] if extra else [])]
        for schema in schemas:
            command += ['--files', str(source/schema)]
        subprocess.run(command, check=True)
        subprocess.run([sys.executable, str(a.src/'tools/build/fuchsia/generate-bsd.py'),
                        '--json', str(ir), '--root', str(generated), '--c',
                        '--fidlgen-cpp', str(a.tools/'fidlgen_cpp')], check=True)
        write_stamps(generated, [Path(s) if Path(s).is_absolute() else source/s
                                 for s in schemas], extra[0] if extra else [])
        expected, current = contents(generated), contents(destination)
        differences += [name+'/'+item for item in sorted(expected.keys() | current.keys())
                        if expected.get(item) != current.get(item)]
        count += len(expected)
        outputs.append((generated, destination))
    if differences and not a.write:
        p.exit(1, 'Generated bindings are stale or hand-edited; run '
               'make -C tools/build/fuchsia regen and commit the result:\n' +
               '\n'.join(differences) + '\n')
    if a.write:
        # Generate all projects successfully before replacing owned outputs.
        for generated, destination in outputs:
            if destination.exists():
                shutil.rmtree(destination)
            shutil.copytree(generated, destination)
    print(f'Native runtime/provider bindings: {count} generated files match; '
          f'{len(evolutions)} next schemas are additive at bsd:1: PASS')
