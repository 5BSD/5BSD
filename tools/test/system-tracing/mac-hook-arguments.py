"""Generate MAC hook argument metadata from the policy ABI; --check checks drift."""
import argparse,json,re
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--src',type=Path,default=Path('/usr/src'));p.add_argument('--output',type=Path);p.add_argument('--check',action='store_true');a=p.parse_args();r=a.src;o=a.output or r
s=(r/'sys/security/mac/mac_policy.h').read_text();s=re.sub(r'/\*.*?\*/','',s,flags=re.S)
types={}
for m in re.finditer(r'typedef\s+(int|void)\s*\(\*mpo_(\w+)\)\(([^;]*)\);',s):
 args=[]
 for arg in m[3].split(','):
  arg=' '.join(arg.split())
  if arg=='void':continue
  n=re.fullmatch(r'(.+?[ *])([A-Za-z_]\w*)',arg)
  if arg.endswith('*') or ' ' not in arg or re.fullmatch(r'struct \w+',arg):
   args.append(dict(name='arg'+str(len(args)),type=arg));continue
  assert n,(m[2],arg)
  typ=n[1].strip();assert '(' not in typ and '[' not in typ,(m[2],typ)
  args.append(dict(name=n[2],type=typ))
 types[m[2]]=dict(result=m[1],arguments=args)
# Only actual operations, excluding reserved ABI placeholder fields.
hooks={}
for typ,name in re.findall(r'mpo_(\w+)\s+mpo_(\w+)\s*;',s):
 assert typ in types,(typ,name)
 if typ!='placeholder_t':hooks[name]=types[typ]
assert len(hooks)>200
h=['/* SPDX-License-Identifier: BSD-2-Clause */','/* Generated by tools/test/system-tracing/mac-hook-arguments.py. */','#ifndef _SECURITY_MAC_MAC_TRACE_ARGS_H_','#define _SECURITY_MAC_MAC_TRACE_ARGS_H_','', '/* Array storage exists only for the synchronous hook-args probe call. */']
for name,data in hooks.items():
 args=data['arguments'];params=['a'+str(i) for i in range(len(args))]
 casts=[]
 for param,arg in zip(params,args):
  typ=arg['type']
  if typ.startswith('struct ') and '*' not in typ:
   casts.append('(uint64_t)(uintptr_t)&('+param+')');arg['encoding']='address-of-value';continue
  arg['encoding']='pointer' if '*' in typ else 'scalar'
  casts.append('(uint64_t)'+('(uintptr_t)' if '*' in typ else '')+'('+typ+')('+param+')')
 # A sentinel permits a valid array even for zero-argument hooks. Count is zero.
 h += ['#define MAC_HOOK_ARGS_'+name+'(policy'+''.join(', '+x for x in params)+') \\', '\tSDT_PROBE4(mac_framework, , , hook__args, "'+name+'", \\', '\t    (policy)->mpc_name, '+str(len(args))+', \\', '\t    ((const uint64_t[]){ '+', '.join(casts or ['0'])+' }))','']
maxargs=max(len(x['arguments']) for x in hooks.values())
h+=['/* Capture each argument once before exposing it and invoking the policy. */','#define MAC_HOOK_NARG_( '+', '.join(['_'+str(i) for i in range(maxargs+1)]+['n','...'])+') n','#define MAC_HOOK_NARG(...) \\','\tMAC_HOOK_NARG_(_, ##__VA_ARGS__, '+', '.join(map(str,range(maxargs,-1,-1)))+')','#define MAC_HOOK_INVOKE(kind, hook, policy, ...) \\','\t__CONCAT(MAC_HOOK_INVOKE_, MAC_HOOK_NARG(__VA_ARGS__)) \\','\t    (kind, hook, policy, ##__VA_ARGS__)','']
for n in range(maxargs+1):
 params=['a'+str(i) for i in range(n)];saved=['__mac_arg'+str(i) for i in range(n)]
 h+=['#define MAC_HOOK_INVOKE_'+str(n)+'(kind, hook, policy'+''.join(', '+x for x in params)+') \\','\t__extension__ ({ \\']
 h+=['\t\t__auto_type '+v+' = ('+k+'); \\' for k,v in zip(params,saved)]
 h+=['\t\tSDT_PROBE2(mac_framework, , , hook__start, \\','\t\t    __XSTRING(hook), (policy)->mpc_name); \\','\t\t__CONCAT(MAC_HOOK_ARGS_, hook)(policy'+''.join(', '+v for v in saved)+'); \\','\t\tMAC_HOOK_RESULT_ ## kind(hook, policy'+''.join(', '+v for v in saved)+'); \\','\t})','']
h+=['#endif','']
files={'sys/security/mac/mac_trace_args.h':'\n'.join(h),'tools/test/system-tracing/mac-hook-arguments.json':json.dumps(hooks,indent=2)+'\n'}
for name,content in files.items():
 dst=o/name
 if a.check:assert dst.read_text()==content,'regenerate '+str(dst)
 else:dst.parent.mkdir(parents=True,exist_ok=True);dst.write_text(content)
print(len(hooks),'hook contracts;',maxargs,'maximum arguments')
